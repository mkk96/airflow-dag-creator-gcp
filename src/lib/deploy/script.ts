/**
 * Self-contained bash deploy script for Cloud Shell (or any shell with gcloud).
 * Files are embedded as base64 so no user content is ever interpreted by the shell.
 */
import { GENERATOR_NAME, RUNTIME } from "../../config/runtime";
import type { GeneratedBundle } from "../../scenarios/types";
import { buildPlan, type DeployTarget } from "./plan";

/** Single-quote a value for bash. */
export function shq(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

/** UTF-8 safe base64, wrapped at 76 columns. Works in browsers and Node. */
export function toBase64(text: string): string {
  const bytes = new TextEncoder().encode(text);
  let bin = "";
  for (let i = 0; i < bytes.length; i += 0x8000) {
    bin += String.fromCharCode(...bytes.subarray(i, i + 0x8000));
  }
  return (btoa(bin).match(/.{1,76}/g) ?? [""]).join("\n");
}

const SAFE_PATH = /^[A-Za-z0-9_./-]+$/;

function embed(relPath: string, content: string): string[] {
  if (!SAFE_PATH.test(relPath) || relPath.split("/").includes("..")) throw new Error(`Unsafe path ${relPath}`);
  return [`write_file ${shq(relPath)} <<'B64'`, toBase64(content), "B64"];
}

export function renderDeployScript(bundle: GeneratedBundle, t: DeployTarget): string {
  // Defence in depth: values that appear inside double-quoted shell strings.
  if (!/^[A-Za-z0-9_.-]+$/.test(bundle.dagId)) throw new Error("Invalid dag_id for a deploy script.");
  if (t.uploadScripts && bundle.deploy.codeBuckets && !/^[a-z0-9._-]+$/.test(t.codeBucket)) {
    throw new Error("Invalid code bucket for a deploy script.");
  }
  const plan = buildPlan(bundle, t);
  const envVar = bundle.deploy.deployEnvVar;
  const dagId = bundle.dagId;
  const gc = `--location "$REGION" --project "$PROJECT"`;
  const out: string[] = [
    "#!/usr/bin/env bash",
    `# Deploy DAG ${dagId} to Cloud Composer.`,
    `# Generated by ${GENERATOR_NAME} v${RUNTIME.generatorVersion}.`,
    "#",
    "# Run it in Cloud Shell (https://shell.cloud.google.com) or any shell where `gcloud` is",
    "# authenticated as someone with roles/composer.environmentAndStorageObjectAdmin (or",
    "# roles/composer.user + roles/storage.objectAdmin on the environment bucket).",
    "set -euo pipefail",
    "",
    `PROJECT=${shq(t.project)}`,
    `REGION=${shq(t.region)}`,
    `COMPOSER_ENV=${shq(t.environment)}`,
    `TARGET_ENV=${shq(t.targetEnv)}          # value ${envVar} must have on this environment`,
    `SET_DEPLOY_ENV=${t.setDeployEnv ? "true" : "false"}    # true: set ${envVar} if missing/different (restarts Airflow, ~10-25 min)`,
    "",
    "describe() {",
    `  gcloud composer environments describe "$COMPOSER_ENV" ${gc} --format="value($1)"`,
    "}",
    "",
    'echo "==> Checking Composer environment $COMPOSER_ENV ($REGION, $PROJECT)"',
    'DAGS_PREFIX=$(describe config.dagGcsPrefix)',
    'AIRFLOW_URI=$(describe config.airflowUri)',
    `CURRENT_ENV=$(describe config.softwareConfig.envVariables.${envVar})`,
    'echo "    DAG folder: $DAGS_PREFIX"',
    `echo "    ${envVar} on this environment: \${CURRENT_ENV:-<not set>}"`,
    "",
    'if [ "$CURRENT_ENV" != "$TARGET_ENV" ]; then',
    '  if [ "$SET_DEPLOY_ENV" = "true" ]; then',
    `    echo "==> Setting ${envVar}=$TARGET_ENV (asynchronous; Airflow restarts in the next 10-25 min)"`,
    `    gcloud composer environments update "$COMPOSER_ENV" ${gc} \\`,
    `      --update-env-variables="${envVar}=$TARGET_ENV" --async`,
    "  else",
    `    echo "ERROR: ${envVar} is '\${CURRENT_ENV:-<not set>}' but this deploy targets '$TARGET_ENV'." >&2`,
    `    echo "       Without it the DAG would use the wrong environment's values. Re-run with SET_DEPLOY_ENV=true." >&2`,
    "    exit 1",
    "  fi",
    "fi",
    "",
    'WORKDIR=$(mktemp -d)',
    "trap 'rm -rf \"$WORKDIR\"' EXIT",
    'write_file() { mkdir -p "$(dirname "$WORKDIR/$1")"; base64 -d > "$WORKDIR/$1"; }',
    "",
  ];

  const vars = plan.filter((s) => s.kind === "variable");
  for (const s of vars) {
    out.push(
      ...embed("variable.json", s.value),
      `echo "==> ${s.label.replace(/[^A-Za-z0-9 _.-]/g, "")}"`,
      `gcloud composer environments run "$COMPOSER_ENV" ${gc} \\`,
      `  variables set -- ${shq(s.name)} "$(cat "$WORKDIR/variable.json")"`,
      "",
    );
  }

  const scripts = plan.filter((s) => s.kind === "upload" && s.dest === "code");
  if (scripts.length) {
    for (const s of scripts) if (s.kind === "upload" && s.dest === "code") out.push(...embed(s.object, s.content));
    out.push(
      `echo "==> Uploading scripts to gs://${t.codeBucket}/scripts/${dagId}/"`,
      `gcloud storage cp --recursive "$WORKDIR/scripts/${dagId}" ${shq(`gs://${t.codeBucket}/scripts/`)}`,
      "",
    );
  }

  const dagSteps = plan.filter((s) => s.kind === "upload" && s.dest === "dags");
  for (const s of dagSteps) if (s.kind === "upload" && s.dest === "dags") out.push(...embed(`dags/${s.relPath}`, s.content));
  const hasSql = dagSteps.some((s) => s.kind === "upload" && s.dest === "dags" && s.relPath.startsWith("sql/"));
  if (hasSql) {
    out.push('echo "==> Uploading SQL files"', `gcloud storage cp --recursive "$WORKDIR/dags/sql" "$DAGS_PREFIX/"`);
  }
  out.push(
    `echo "==> Uploading the DAG (${dagId}.py) last, so it never appears without its SQL"`,
    `gcloud storage cp "$WORKDIR/dags/${dagId}.py" "$DAGS_PREFIX/${dagId}.py"`,
    "",
    'echo ""',
    `echo "Done. The DAG appears in Airflow within 1-2 minutes (new DAGs start paused):"`,
    `echo "  $AIRFLOW_URI/dags/${dagId}/grid"`,
  );
  if (t.setDeployEnv) {
    out.push(`echo "If ${envVar} was just updated, unpause the DAG only after the environment update finishes."`);
  }
  return out.join("\n") + "\n";
}
