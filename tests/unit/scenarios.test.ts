import { describe, expect, it } from "vitest";
import { exportConfig, importConfig } from "../../src/lib/configIO";
import { isPyIdentifier } from "../../src/lib/python";
import { suggestNames } from "../../src/lib/suggest";
import {
  allFields,
  allSections,
  BQ_INSERT_JOB_TEMPLATE_EXT,
  defaultParams,
  guardTemplateExt,
  sampleParams,
} from "../../src/scenarios/common";
import { PLANNED_SCENARIOS } from "../../src/scenarios/planned";
import { SCENARIOS } from "../../src/scenarios/registry";
import { countIssues, validateParams } from "../../src/validation/validate";

describe.each(SCENARIOS.map((s) => [s.id, s] as const))("scenario %s — contract", (_id, s) => {
  it("has unique field keys, known sections and valid select defaults", () => {
    const fields = allFields(s);
    const keys = fields.map((f) => f.key);
    expect(new Set(keys).size).toBe(keys.length);
    const sections = new Set(allSections(s).map((x) => x.id));
    for (const f of fields) {
      expect(sections.has(f.section), `${f.key} section ${f.section}`).toBe(true);
      if (f.type === "select") {
        expect(f.options?.some((o) => o.value === f.default), `${f.key} default`).toBe(true);
      }
      if (f.envSpecific) expect(isPyIdentifier(f.key), `${f.key} must be an identifier`).toBe(true);
    }
  });

  it("defaults are valid and generate a DAG", () => {
    const p = defaultParams(s);
    expect(countIssues(validateParams(s, p)).errors).toBe(0);
    const b = s.generate(p);
    expect(b.files.some((f) => f.path === `dags/${b.dagId}.py`)).toBe(true);
  });

  it("has at least one sample and all samples validate", () => {
    const names = Object.keys(s.samples);
    expect(names.length).toBeGreaterThan(0);
    for (const n of names) {
      const r = validateParams(s, sampleParams(s, n));
      const errors = Object.entries(r).flatMap(([k, i]) => i.errors.map((e) => `${k}: ${e}`));
      expect(errors, n).toEqual([]);
    }
  });

  it("generated DAG follows the conventions", () => {
    for (const n of Object.keys(s.samples)) {
      const b = s.generate(sampleParams(s, n));
      const py = b.files.find((f) => f.role === "dag")!.content;
      expect(py).toContain(`Scenario : ${s.id}`);
      expect(py).toMatch(/Generated by Airflow DAG Creator for GCP v\d+\.\d+\.\d+/);
      expect(py).toContain("with DAG(\n");
      expect(py).toContain(") as dag:\n");
      expect(py).toContain(`DAG_ID = "${b.dagId}"`);
      expect(py).not.toMatch(/Variable\.get\(/);
      expect(py).not.toMatch(/airflow\.contrib/);
      expect(py).toContain('"on_failure_callback": notify_failure');
      expect(py.split("\n").some((l) => /\t/.test(l))).toBe(false);
      for (const f of b.files) expect(f.path.split("/")).not.toContain("..");
      if (b.files.some((f) => f.role === "sql")) {
        expect(b.needsZip).toBe(true);
        expect(py).toContain("template_searchpath=[SQL_DIR]");
      }
    }
  });

  it("exports and re-imports config losslessly", () => {
    const p = sampleParams(s, Object.keys(s.samples)[0]);
    const r = importConfig(exportConfig(s, p));
    expect(r.scenario.id).toBe(s.id);
    expect(r.params).toEqual(p);
    expect(r.notes).toEqual([]);
  });

  it("suggests convention-compliant names", () => {
    const p = { ...defaultParams(s), org: "acme", env: "prd", domain: "sales", schedule_preset: "@daily" };
    const sug = suggestNames(s, p);
    expect(sug.dag_id).toBe(`sales_${s.naming.source}_to_${s.naming.target}_daily`);
    const r = validateParams(s, { ...p, ...sug });
    for (const k of Object.keys(sug)) expect(r[k]?.warnings ?? [], k).toEqual([]);
  });
});

describe("template_ext guard", () => {
  it("rewrites trailing template extensions as Jinja literals", () => {
    expect(guardTemplateExt("gs://b/x/*.json", BQ_INSERT_JOB_TEMPLATE_EXT)).toBe("gs://b/x/*{{ '.json' }}");
    expect(guardTemplateExt("gs://b/q.sql", BQ_INSERT_JOB_TEMPLATE_EXT)).toBe("gs://b/q{{ '.sql' }}");
    expect(guardTemplateExt("gs://b/x/*.csv", BQ_INSERT_JOB_TEMPLATE_EXT)).toBe("gs://b/x/*.csv");
  });
  it("no generated sourceUri ends with a template extension", () => {
    for (const s of SCENARIOS) {
      for (const n of Object.keys(s.samples)) {
        const py = s.generate(sampleParams(s, n)).files.find((f) => f.role === "dag")!.content;
        expect(py).not.toMatch(/"gs:\/\/[^"]*\.(json|sql)"/);
      }
    }
  });
});

describe("config import safety", () => {
  it("rejects foreign JSON and ignores unknown or mistyped fields", () => {
    expect(() => importConfig("not json")).toThrow();
    expect(() => importConfig('{"kind":"other"}')).toThrow();
    const s = SCENARIOS[0];
    const r = importConfig(
      JSON.stringify({ kind: "airflow-dag-creator-gcp/config", scenario: s.id, params: { evil: 1, retries: "3" } }),
    );
    expect(r.params.retries).toBe(defaultParams(s).retries);
    expect(r.notes.length).toBe(2);
  });
});

describe("registry", () => {
  it("scenario ids are unique across implemented and planned", () => {
    const ids = [...SCENARIOS.map((s) => s.id), ...PLANNED_SCENARIOS.map((s) => s.id)];
    expect(new Set(ids).size).toBe(ids.length);
    expect(SCENARIOS.length + PLANNED_SCENARIOS.length).toBe(14);
  });
});
